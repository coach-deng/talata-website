#!/usr/bin/env python3
"""
Build /gallery from data/gallery.json (2 Nov 2026).

WHY THIS EXISTS
The gallery was hand-written HTML. New game photos sat on the Mac for days
because putting them up meant editing the page by hand in a chat. Now a
section is one entry in data/gallery.json, newest first, and the dash's
Website card (Approve) can add one without touching the page.

A SECTION
    {"id": "2026-10-30-men-sisu-2",          anchor on the page, optional
     "date": "2026-10-30",                   when it happened, optional
     "title": "Men v SISU 2, October 2026",  plain text
     "text": "one line",                     plain text, optional
     "link": {"href": "/games", "label": "Every score"},   optional
     "note_html": "...",                     trusted HTML instead of text + link (old sections)
     "photos": [{"src": "/images/2026-11/site/x.jpg", "alt": "...", "w": 1600, "h": 900}],
     "source": "intake:<folder>"}            where it came from, never shown

Photos: group frames only, never a named child's portrait
(SecondBrain/Talata/_references/photo-consent.md). Every photo needs alt, w and h.

    python3 tools/apply-gallery.py            write the page
    python3 tools/apply-gallery.py --check    exit 1 if the page is behind the list
    python3 tools/apply-gallery.py --import   one time: read the hand-written page into the list
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data/gallery.json"
PAGE = ROOT / "gallery.html"
START = "<!-- TALATA:GALLERY:START — generated by tools/apply-gallery.py from data/gallery.json, do not hand-edit -->"
END = "<!-- TALATA:GALLERY:END -->"


def esc(t):
    return html.escape(str(t), quote=True)


def render(doc):
    out, first = [], True
    for s in doc["sections"]:
        if not s.get("photos"):
            raise SystemExit("apply-gallery: section %r has no photos" % s.get("title"))
        anchor = ' id="%s"' % esc(s["id"]) if s.get("id") else ""
        out.append('    <h2 class="section-label"%s>%s</h2>' % (anchor, esc(s["title"])))
        note = s.get("note_html")
        if note is None and (s.get("text") or s.get("link")):
            parts = [esc(s["text"])] if s.get("text") else []
            if s.get("link"):
                parts.append('<a href="%s">%s</a>' % (esc(s["link"]["href"]), esc(s["link"]["label"])))
            note = " ".join(parts)
        if note:
            out.append('    <p class="section-note">%s</p>' % note)
        out.append('    <div class="grid">')
        for p in s["photos"]:
            for k in ("src", "alt", "w", "h"):
                if not p.get(k):
                    raise SystemExit("apply-gallery: a photo in %r has no %s" % (s.get("title"), k))
            load = 'decoding="async" fetchpriority="high"' if first else 'loading="lazy" decoding="async"'
            first = False
            out.append('      <img src="%s" alt="%s" %s width="%d" height="%d">'
                       % (esc(p["src"]), esc(p["alt"]), load, int(p["w"]), int(p["h"])))
        out.append("    </div>")
        out.append("")
    return "\n".join(out).rstrip("\n")


def import_page():
    """Read the hand-written sections once, so nothing on the page is lost."""
    src = PAGE.read_text(encoding="utf-8")
    body = src[src.index('<div class="gallery-wrap">'):src.index('<div class="cta-band">')]
    secs = []
    for m in re.finditer(r'<h2 class="section-label"(?: id="([^"]+)")?>(.*?)</h2>\s*'
                         r'(?:<p class="section-note">(.*?)</p>\s*)?<div class="grid">(.*?)</div>', body, re.S):
        photos = []
        for img in re.finditer(r"<img\b([^>]*)>", m.group(4)):
            a = dict(re.findall(r'(\w[\w-]*)="([^"]*)"', img.group(1)))
            photos.append({"src": a["src"], "alt": html.unescape(a["alt"]), "w": int(a["width"]), "h": int(a["height"])})
        sec = {"title": html.unescape(re.sub(r"<[^>]+>", "", m.group(2)))}
        if m.group(1):
            sec["id"] = m.group(1)
        if m.group(3):
            sec["note_html"] = m.group(3).strip()
        sec["photos"] = photos
        secs.append(sec)
    return {"sections": secs}


def main(argv):
    if "--import" in argv:
        doc = import_page()
        DATA.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print("apply-gallery: imported %d sections, %d photos"
              % (len(doc["sections"]), sum(len(s["photos"]) for s in doc["sections"])))
        return 0
    doc = json.loads(DATA.read_text(encoding="utf-8"))
    src = PAGE.read_text(encoding="utf-8")
    if START not in src:
        raise SystemExit("apply-gallery: gallery.html has no TALATA:GALLERY markers")
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    out = pat.sub(lambda _: "%s\n%s\n    %s" % (START, render(doc), END), src, count=1)
    if out == src:
        print("apply-gallery: gallery.html is current")
        return 0
    if "--check" in argv:
        print("apply-gallery: gallery.html is behind data/gallery.json. Run python3 tools/apply-gallery.py")
        return 1
    PAGE.write_text(out, encoding="utf-8")
    print("apply-gallery: wrote %d sections" % len(doc["sections"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
